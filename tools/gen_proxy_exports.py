"""Generates proxy/exports.inl from the real dwmapi.dll of this Windows.
usage: python tools/gen_proxy_exports.py [dumpbin.exe]   (finds dumpbin through vswhere when not given)"""
import os, re, subprocess, sys
BS = chr(92)
def find_dumpbin():
    vw = os.path.join(os.environ.get('ProgramFiles(x86)', r'C:' + BS + 'Program Files (x86)'), 'Microsoft Visual Studio', 'Installer', 'vswhere.exe')
    root = subprocess.check_output([vw, '-latest', '-products', '*', '-property', 'installationPath'], text=True).strip()
    for d, _, fs in os.walk(os.path.join(root, 'VC', 'Tools', 'MSVC')):
        if 'dumpbin.exe' in fs and 'Hostx64' + BS + 'x64' in d: return os.path.join(d, 'dumpbin.exe')
dumpbin = sys.argv[1] if len(sys.argv) > 1 else find_dumpbin()
sysdll = os.path.join(os.environ.get('SystemRoot', 'C:' + BS + 'Windows'), 'System32', 'dwmapi.dll')
text = subprocess.check_output([dumpbin, '/exports', sysdll], text=True, errors='ignore')
out = []
for l in text.split('\n'):
    m = re.match(r'\s+(\d+)\s+([0-9A-F]+)\s+([0-9A-F]{8})\s+(\w+)\s*$', l)
    if m: out.append((int(m.group(1)), m.group(4))); continue
    m = re.match(r'\s+(\d+)\s+([0-9A-F]{8})\s+\[NONAME\]', l)
    if m: out.append((int(m.group(1)), None))
out.sort()
target = 'C:' + BS * 2 + 'Windows' + BS * 2 + 'System32' + BS * 2 + 'dwmapi'
h = ['// Generated by tools/gen_proxy_exports.py from the real dwmapi.dll of this Windows (dumpbin /exports): every export is forwarded to the',
     '// system library by full path, so the proxy needs no code of its own for them. Re-generate on another Windows build if the game fails to start.']
for o, n in out:
    if n: h.append('#pragma comment(linker, "/EXPORT:%s=%s.%s,@%d")' % (n, target, n, o))
    else: h.append('#pragma comment(linker, "/EXPORT:_ord%d=%s.#%d,@%d,NONAME")' % (o, target, o, o))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'proxy', 'exports.inl'), 'w').write('\n'.join(h) + '\n')
print(len(out), 'exports')
